const reverseTranslations = Object.fromEntries(
    Object.entries(translations).map(([vietnamese, english]) => [english, vietnamese])
);

const originalTextNodes = new WeakMap();
const originalAttributes = new WeakMap();
const pageTitle = document.querySelector('title');
const originalPageTitle = pageTitle?.textContent || '';

const translateValue = (value, language) => {
    if (language === 'en') {
        return translations[value] || value;
    }

    return reverseTranslations[value] || value;
};

const applyLanguage = (language) => {
    document.documentElement.lang = language === 'en' ? 'en' : 'vi';
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    let textNode = walker.nextNode();

    while (textNode) {
        if (!originalTextNodes.has(textNode)) {
            originalTextNodes.set(textNode, textNode.nodeValue);
        }

        const sourceText = originalTextNodes.get(textNode);
        const trimmedText = sourceText.trim();

        if (trimmedText) {
            const translatedText = language === 'en' ? (translations[trimmedText] || trimmedText) : trimmedText;
            textNode.nodeValue = sourceText.replace(trimmedText, translatedText);
        }

        textNode = walker.nextNode();
    }

    document.querySelectorAll('img[alt], [aria-label]').forEach((element) => {
        let sourceAttributes = originalAttributes.get(element);

        if (!sourceAttributes) {
            sourceAttributes = new Map();
            originalAttributes.set(element, sourceAttributes);
        }

        ['alt', 'aria-label'].forEach((attribute) => {
            if (element.hasAttribute(attribute)) {
                if (!sourceAttributes.has(attribute)) {
                    sourceAttributes.set(attribute, element.getAttribute(attribute));
                }

                const sourceValue = sourceAttributes.get(attribute);
                element.setAttribute(attribute, language === 'en' ? (translations[sourceValue] || sourceValue) : sourceValue);
            }
        });
    });

    if (pageTitle) {
        pageTitle.textContent = language === 'en'
            ? (translations[originalPageTitle] || originalPageTitle)
            : originalPageTitle;
    }
};

const readPreference = (key) => {
    try {
        return window.localStorage.getItem(key);
    } catch (error) {
        console.warn(`Unable to read saved preference "${key}".`, error);
        return null;
    }
};

const savePreference = (key, value) => {
    try {
        window.localStorage.setItem(key, value);
    } catch (error) {
        console.warn(`Unable to save preference "${key}".`, error);
    }
};

const themeToggle = document.querySelector('.theme-toggle');
const languageToggle = document.querySelector('.language-toggle');
const storedTheme = readPreference('site-theme');
const storedLanguage = readPreference('site-language');
let currentTheme = storedTheme === 'dark' ? 'dark' : 'light';
let currentLanguage = storedLanguage === 'en' ? 'en' : 'vi';

const updateThemeControl = () => {
    if (!themeToggle) {
        return;
    }

    const darkModeEnabled = currentTheme === 'dark';
    themeToggle.textContent = darkModeEnabled ? 'Giao diện sáng' : 'Giao diện tối';
    themeToggle.setAttribute('aria-label', darkModeEnabled ? 'Bật giao diện sáng' : 'Bật giao diện tối');
    themeToggle.setAttribute('aria-pressed', String(darkModeEnabled));

    if (currentLanguage === 'en') {
        themeToggle.textContent = darkModeEnabled ? 'Light mode' : 'Dark mode';
        themeToggle.setAttribute('aria-label', darkModeEnabled ? 'Switch to light mode' : 'Switch to dark mode');
    }
};

const updateLanguageControl = () => {
    if (!languageToggle) {
        return;
    }

    languageToggle.textContent = currentLanguage === 'vi' ? 'EN' : 'VI';
    languageToggle.setAttribute(
        'aria-label',
        currentLanguage === 'vi' ? 'Switch to English' : 'Chuyển sang tiếng Việt'
    );
};

const notifyLanguageChange = () => {
    document.dispatchEvent(new CustomEvent('site-language-change', {
        detail: { language: currentLanguage }
    }));
};

document.documentElement.dataset.theme = currentTheme;
applyLanguage(currentLanguage);
updateThemeControl();
updateLanguageControl();
notifyLanguageChange();

if (themeToggle) {
    themeToggle.addEventListener('click', () => {
        currentTheme = currentTheme === 'light' ? 'dark' : 'light';
        document.documentElement.dataset.theme = currentTheme;
        savePreference('site-theme', currentTheme);
        updateThemeControl();
    });
}

if (languageToggle) {
    languageToggle.addEventListener('click', () => {
        currentLanguage = currentLanguage === 'vi' ? 'en' : 'vi';
        savePreference('site-language', currentLanguage);
        applyLanguage(currentLanguage);
        updateThemeControl();
        updateLanguageControl();
        notifyLanguageChange();
    });
}

document.querySelectorAll('header nav').forEach((nav) => {
    const toggle = nav.querySelector('.nav-toggle');
    const links = nav.querySelector('.nav-links');

    if (!toggle || !links) {
        return;
    }

    const closeMenu = () => {
        nav.classList.remove('nav--open');
        toggle.setAttribute('aria-expanded', 'false');
        toggle.setAttribute('aria-label', translateValue('Mở menu', currentLanguage));
    };

    toggle.addEventListener('click', () => {
        const isOpen = toggle.getAttribute('aria-expanded') === 'true';
        nav.classList.toggle('nav--open', !isOpen);
        toggle.setAttribute('aria-expanded', String(!isOpen));
        toggle.setAttribute('aria-label', translateValue(isOpen ? 'Mở menu' : 'Đóng menu', currentLanguage));
    });

    links.addEventListener('click', (event) => {
        if (event.target instanceof Element && event.target.closest('a')) {
            closeMenu();
        }
    });

    document.addEventListener('click', (event) => {
        if (event.target instanceof Node && !nav.contains(event.target)) {
            closeMenu();
        }
    });

    document.addEventListener('keydown', (event) => {
        if (event.key === 'Escape') {
            closeMenu();
        }
    });

    window.matchMedia('(min-width: 768px)').addEventListener('change', closeMenu);
});

let backToTopButton = document.querySelector('.back-to-top');

if (!backToTopButton) {
    backToTopButton = document.createElement('button');
    backToTopButton.className = 'back-to-top';
    backToTopButton.type = 'button';
    backToTopButton.textContent = '↑ Lên đầu trang';
    backToTopButton.setAttribute('aria-label', 'Lên đầu trang');
    document.body.append(backToTopButton);
    applyLanguage(currentLanguage);
    updateThemeControl();
    updateLanguageControl();
}

if (backToTopButton) {
    const updateBackToTopVisibility = () => {
        backToTopButton.classList.toggle('back-to-top--visible', window.scrollY > 300);
    };

    backToTopButton.addEventListener('click', () => {
        window.scrollTo({ top: 0, behavior: 'smooth' });
    });

    window.addEventListener('scroll', updateBackToTopVisibility, { passive: true });
    updateBackToTopVisibility();
}

const revealElements = document.querySelectorAll(
    '.home-card, .profile-section, .school-gallery__item, .hobby-card, .football-section'
);

if (revealElements.length > 0) {
    if ('IntersectionObserver' in window) {
        const revealObserver = new IntersectionObserver((entries, observer) => {
            entries.forEach((entry) => {
                if (entry.isIntersecting) {
                    entry.target.classList.add('is-visible');
                    observer.unobserve(entry.target);
                }
            });
        }, { threshold: 0.12 });

        revealElements.forEach((element) => {
            element.classList.add('reveal-on-scroll');
            revealObserver.observe(element);
        });
    }
}

const slideshow = document.querySelector('.school-slideshow');
const schoolGallery = document.querySelector('.school-gallery__grid');

if (slideshow && schoolGallery) {
    const slides = Array.from(schoolGallery.querySelectorAll('.school-gallery__item')).map((item) => {
        const image = item.querySelector('img');
        const caption = item.querySelector('figcaption');

        if (!image) {
            return null;
        }

        return {
            src: image.getAttribute('src'),
            alt: image.getAttribute('alt') || caption?.textContent?.trim() || 'Ảnh trường học',
            caption: caption?.textContent?.trim() || image.getAttribute('alt') || 'Ảnh trường học'
        };
    }).filter((slide) => slide && slide.src);

    const slideshowImage = slideshow.querySelector('.school-slideshow__image');
    const slideshowCaption = slideshow.querySelector('.school-slideshow__caption');
    const slideshowStatus = slideshow.querySelector('.school-slideshow__status');
    const previousButton = slideshow.querySelector('.school-slideshow__previous');
    const nextButton = slideshow.querySelector('.school-slideshow__next');
    const pauseButton = slideshow.querySelector('.school-slideshow__pause');

    if (slides.length > 0 && slideshowImage && slideshowCaption && slideshowStatus
        && previousButton && nextButton && pauseButton) {
        let currentSlide = 0;
        let intervalId;
        let isPaused = false;

        const showSlide = (index) => {
            currentSlide = (index + slides.length) % slides.length;
            const slide = slides[currentSlide];
            slideshowImage.src = slide.src;
            slideshowImage.alt = translateValue(slide.alt, currentLanguage);
            slideshowCaption.textContent = translateValue(slide.caption, currentLanguage);
            slideshowStatus.textContent = `${translateValue('Ảnh', currentLanguage)} ${currentSlide + 1} / ${slides.length}`;
        };

        const stopSlideshow = () => {
            window.clearInterval(intervalId);
            intervalId = undefined;
        };

        const startSlideshow = () => {
            if (intervalId || isPaused || document.hidden || slides.length < 2) {
                return;
            }

            intervalId = window.setInterval(() => {
                showSlide(currentSlide + 1);
            }, 3000);
        };

        previousButton.addEventListener('click', () => showSlide(currentSlide - 1));
        nextButton.addEventListener('click', () => showSlide(currentSlide + 1));
        pauseButton.addEventListener('click', () => {
            isPaused = !isPaused;
            pauseButton.textContent = translateValue(isPaused ? 'Phát trình chiếu' : 'Tạm dừng', currentLanguage);
            pauseButton.setAttribute(
                'aria-label',
                translateValue(isPaused ? 'Phát trình chiếu' : 'Tạm dừng trình chiếu', currentLanguage)
            );

            if (isPaused) {
                stopSlideshow();
            } else {
                startSlideshow();
            }
        });

        slideshow.addEventListener('mouseenter', stopSlideshow);
        slideshow.addEventListener('mouseleave', startSlideshow);
        slideshow.addEventListener('focusin', stopSlideshow);
        slideshow.addEventListener('focusout', (event) => {
            if (event.relatedTarget instanceof Node && !slideshow.contains(event.relatedTarget)) {
                startSlideshow();
            }
        });

        document.addEventListener('visibilitychange', () => {
            if (document.hidden) {
                stopSlideshow();
            } else {
                startSlideshow();
            }
        });

        document.addEventListener('site-language-change', () => {
            showSlide(currentSlide);
            pauseButton.textContent = translateValue(isPaused ? 'Phát trình chiếu' : 'Tạm dừng', currentLanguage);
            pauseButton.setAttribute(
                'aria-label',
                translateValue(isPaused ? 'Phát trình chiếu' : 'Tạm dừng trình chiếu', currentLanguage)
            );
        });

        showSlide(0);
        startSlideshow();
    }
}